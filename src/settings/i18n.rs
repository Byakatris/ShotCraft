#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Language {
    En,
    Uk,
    Es,
    Fr,
    De,
    Pl,
    It,
    Pt,
    Tr,
    Nl,
}

impl Language {
    pub const ALL: [Self; 10] = [
        Self::En,
        Self::Uk,
        Self::Es,
        Self::Fr,
        Self::De,
        Self::Pl,
        Self::It,
        Self::Pt,
        Self::Tr,
        Self::Nl,
    ];

    pub fn code(self) -> &'static str {
        match self {
            Self::En => "en",
            Self::Uk => "uk",
            Self::Es => "es",
            Self::Fr => "fr",
            Self::De => "de",
            Self::Pl => "pl",
            Self::It => "it",
            Self::Pt => "pt",
            Self::Tr => "tr",
            Self::Nl => "nl",
        }
    }

    pub fn from_code(s: &str) -> Self {
        Self::ALL
            .into_iter()
            .find(|l| l.code() == s.trim())
            .unwrap_or(Self::En)
    }

    pub fn label(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Uk => "Українська",
            Self::Es => "Español",
            Self::Fr => "Français",
            Self::De => "Deutsch",
            Self::Pl => "Polski",
            Self::It => "Italiano",
            Self::Pt => "Português",
            Self::Tr => "Türkçe",
            Self::Nl => "Nederlands",
        }
    }
}

