impl Strings {
    pub const fn primary_mod_label() -> &'static str {
        if cfg!(target_os = "macos") {
            "Cmd"
        } else {
            "Ctrl"
        }
    }

    pub fn with_mod(template: &str) -> String {
        template.replace("{MOD}", Self::primary_mod_label())
    }

    pub const fn for_lang(lang: Language) -> &'static Self {
        match lang {
            Language::Uk => &STRINGS_UK,
            Language::Es => &STRINGS_ES,
            Language::Fr => &STRINGS_FR,
            Language::De => &STRINGS_DE,
            Language::Pl => &STRINGS_PL,
            Language::It => &STRINGS_IT,
            Language::Pt => &STRINGS_PT,
            Language::Tr => &STRINGS_TR,
            Language::Nl => &STRINGS_NL,
            Language::En => &STRINGS_EN,
        }
    }
}

